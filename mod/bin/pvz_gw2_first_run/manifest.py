"""Manifest writers.

Two outputs:
    - cache/manifest.json  — machine-readable record of what the extractor did
    - scripts/vscripts/pvz_gw2_manifest.nut — one-liner the in-game VScript reads

The .nut file is deliberately tiny so VScript's IncludeScript loads it fast.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any


def write_manifest(path: Path, data: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, sort_keys=True), encoding="utf-8")


def write_vscript_stub(path: Path, count: int) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    # Squirrel syntax. `::` makes MANIFEST_COUNT a root-table global so
    # pvz_gw2_welcome.nut's IncludeScript picks it up.
    path.write_text(f"// auto-generated by pvz_gw2_first_run\n"
                    f"::MANIFEST_COUNT <- {int(count)};\n",
                    encoding="utf-8")
